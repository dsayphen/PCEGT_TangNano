// tb_gbc_core - self-checking testbench for rtl/gbc/gbc_core.v
//
// * Behavioural model of the SDRAM "port B" (rtl/nestang/src/sdram_nes.v):
//   mem_rd / mem_wr are levels sampled once every 2 clk; an access starts on
//   a 0->1 transition seen between two samples; read data becomes valid after
//   a random latency of at most 5 clk from the rising edge of mem_rd (often
//   exactly 5 = worst case) and is garbage before. The model also checks the
//   protocol (hold >= 2 clk, low >= 2 clk, stable address/data, rd&wr never
//   both high, at most one access per 6 clk, no writes into the ROM area).
// * A hand-assembled test ROM (MBC5, CGB flag) exercising double speed,
//   WRAM banking, CGB palettes, MBC5 ROM banking, cart RAM, GDMA/HDMA,
//   OAM DMA and the display; then the same ROM in DMG mode.
//
// Negative test: compile with -DGBC_BREAK_LATENCY (DUT samples read data one
// clk too early) -> this testbench must fail.
`timescale 1ns / 1ps

module tb_gbc_core;

    reg clk = 1'b0;
    always #23.148 clk = ~clk;          // 21.6 MHz

    reg        reset = 1'b1;
    reg        pause = 1'b0;
    reg        cgb_enable = 1'b1;
    reg  [7:0] buttons = 8'h00;
    wire [21:0] mem_addr;
    wire        mem_rd, mem_wr;
    wire [7:0]  mem_wdata;
    reg  [7:0]  mem_rdata = 8'h00;
    wire        pix_valid, hsync, vsync, cgb_mode, pal_wr;
    wire [5:0]  pix_index;
    wire [6:0]  pal_wr_addr;
    wire [7:0]  pal_wr_data;
    wire [15:0] audio_l, audio_r;

    gbc_core #(.MEM_LAT(5)) dut (
        .clk(clk), .reset(reset), .pause(pause), .cgb_enable(cgb_enable),
        .cart_type(8'h19), .rom_size(8'h02), .ram_size(8'h02), .buttons(buttons),
        .mem_addr(mem_addr), .mem_rd(mem_rd), .mem_wr(mem_wr),
        .mem_wdata(mem_wdata), .mem_rdata(mem_rdata),
        .pix_valid(pix_valid), .pix_index(pix_index), .hsync(hsync), .vsync(vsync),
        .cgb_mode(cgb_mode), .pal_wr(pal_wr), .pal_wr_addr(pal_wr_addr),
        .pal_wr_data(pal_wr_data), .audio_l(audio_l), .audio_r(audio_r)
    );

    // ------------------------------------------------------------------
    // Test program (generated by a small hand assembler), placed at 0x150
    // ------------------------------------------------------------------
    localparam int PROG_LEN = 605;
    localparam [8*PROG_LEN-1:0] PROG = {
        256'hF3FE11C23B0331FEFF1E01AFE0403E01E04D1000F04DFEFEC234031E023E11EA,
        256'h00C03E02E0703E22EA00D03E07E0703E77EA00D0FA00D0FE77C23403F070FEFF,
        256'hC234033E02E070FA00D0FE22C23403FA00F0FE22C23403FA00C0FE11C23403FA,
        256'h00E0FE11C23403F070FEFAC234031E033E80E0683E12E0693E34E0693E56E069,
        256'h3E88E06A3E9AE06B3EBCE06BF068FEC3C234033E01E068F069FE34C23403F068,
        256'hFE41C234033E09E06AF06BFEBCC23403F06AFE49C234031E043E0BEA0020FA00,
        256'h40FEB3C23403FAFF7FFE3CC234033E01EA0020FA0040FEB1C234031E053E0AEA,
        256'h00003EC5EA00A0FA00A0FEC5C23403AFEA0000FA00A0FEFFC234033E0AEA0000,
        256'hFA00A0FEC5C234031E062100C13E400610223C0520FB3E01E04F3EC1E0513E00,
        256'hE0523E88E0533E00E0543E00E055F055FEFFC23403FA0088FE40C23403FA0F88,
        256'hFE4FC234033E00E04FFA0088FE00C234031E073E10E0513E00E0523E80E0533E,
        256'h00E0543E00E0553E14E0513E00E0523E98E0533E00E0543E3FE055F055FEFFC2,
        256'h34033E01E04F3E18E0513E00E0523E98E0533E00E0543E3FE055FAFF9BFE05C2,
        256'h34033E00E04FFA0F80FEFFC234031E083E12EA00C23E34EA9FC23EC2E0460650,
        256'h0520FDFA00FEFE12C23403FA9FFEFE34C234031E093E91E0403EA5EA00A03E01,
        256'hE08018FE7BF680E08018FE31FEFF1E21AFE040F04DFEFFC23403F070FEFFC234,
        256'h033E5AEA00C03EA5EAFFDDFA00C0FE5AC23403FAFFDDFEA5C23403FAFFFDFEA5,
        256'hC23403FA00E0FE5AC234031E222100803EFF0610220520FC210098010004AF22,
        232'h0B78B120F9FA0F80FEFFC234031E233E40E0473E91E0403E01E08018FE
    };

    // ------------------------------------------------------------------
    // SDRAM port-B model
    // ------------------------------------------------------------------
    reg [7:0] mem [0:22'h3FFFFF];
    integer cyc = 0;
    integer rise_t = -100, last_rise_t = -100, data_t = -1;
    integer hi_cnt = 0, lo_cnt = 100, lat;
    reg     req_q = 1'b0, smp_q = 1'b0, phase = 1'b0, garbage = 1'b0;
    reg     acc_wr;
    reg [21:0] a_lat;
    reg [7:0]  d_lat, data_v;
    integer n_rd = 0, n_wr = 0, n_worst = 0;
    reg     model_reset = 1'b1;

    always @(posedge clk) begin
        cyc = cyc + 1;
        if (model_reset) begin
            req_q = 1'b0; smp_q = 1'b0; data_t = -1; garbage = 1'b0;
            last_rise_t = -100; lo_cnt = 100; hi_cnt = 0;
        end else begin
            if (mem_rd && mem_wr) $fatal(1, "SDRAM model: mem_rd and mem_wr both high");
            if ((mem_rd || mem_wr) && !req_q) begin
                // DUT raised the request at the previous edge
                rise_t = cyc - 1;
                if (lo_cnt < 2) $fatal(1, "SDRAM model: request low for only %0d clk", lo_cnt);
                if (rise_t - last_rise_t < 6)
                    $fatal(1, "SDRAM model: new access %0d clk after previous one", rise_t - last_rise_t);
                last_rise_t = rise_t;
                a_lat = mem_addr; d_lat = mem_wdata; acc_wr = mem_wr;
                hi_cnt = 0;
            end
            if (mem_rd || mem_wr) begin
                hi_cnt = hi_cnt + 1; lo_cnt = 0;
                if (mem_addr !== a_lat) $fatal(1, "SDRAM model: address changed while request held");
                if (mem_wr && mem_wdata !== d_lat) $fatal(1, "SDRAM model: wdata changed while request held");
                if (mem_wr !== acc_wr) $fatal(1, "SDRAM model: request type changed");
            end else begin
                if (req_q && hi_cnt < 2) $fatal(1, "SDRAM model: request held only %0d clk", hi_cnt);
                lo_cnt = lo_cnt + 1;
            end
            req_q = mem_rd || mem_wr;

            phase = ~phase;
            if (phase) begin
                if ((mem_rd || mem_wr) && !smp_q) begin
                    if (mem_wr) begin
                        if (mem_addr < 22'h3D8000) $fatal(1, "SDRAM model: write into ROM area %h", mem_addr);
                        mem[mem_addr] = mem_wdata;
                        n_wr = n_wr + 1;
                    end else begin
                        // data valid between (sample time) and rise+5, worst case favoured
                        lat = (cyc - rise_t) + ($urandom % (6 - (cyc - rise_t)));
                        if ($urandom % 2) lat = 5;
                        if (lat == 5) n_worst = n_worst + 1;
                        data_t = rise_t + lat;
                        data_v = mem[mem_addr];
                        garbage = 1'b1;
                        n_rd = n_rd + 1;
                    end
                end
                smp_q = mem_rd || mem_wr;
            end
            if (data_t == cyc) begin
                mem_rdata <= data_v;
                garbage = 1'b0;
            end else if (garbage)
                mem_rdata <= $urandom;
        end
    end

    // ------------------------------------------------------------------
    // Monitors
    // ------------------------------------------------------------------
    reg        pass_flag = 1'b0;
    integer    pal_n = 0;
    reg [6:0]  pal_a [0:255];
    reg [7:0]  pal_d [0:255];
    reg [5:0]  exp_pix = 6'h00;

    always @(posedge clk) begin
        if (!reset && dut.wr_stb && dut.cpu_a == 16'hFF80) begin
            if (dut.cpu_dout[7])
                $fatal(1, "test program reported failure in test %0d (cgb=%0d)", dut.cpu_dout[6:0], cgb_mode);
            if (dut.cpu_dout == 8'h01) pass_flag <= 1'b1;
        end
        if (!reset && pal_wr) begin
            if (pal_n < 256) begin
                pal_a[pal_n] = pal_wr_addr;
                pal_d[pal_n] = pal_wr_data;
            end
            pal_n = pal_n + 1;
        end
    end

    // frame statistics between vsync rising edges
    integer frames = 0;
    integer f_pix = 0, f_bad = 0, f_hs = 0, f_en = 0, f_clk = 0;
    integer l_pix, l_bad, l_hs, l_en, l_clk;
    reg vs_q = 1'b0, hs_q = 1'b0;
    always @(posedge clk) begin
        if (reset) begin
            frames = 0; f_pix = 0; f_bad = 0; f_hs = 0; f_en = 0; f_clk = 0;
        end else begin
            if (vsync && !vs_q) begin
                frames = frames + 1;
                l_pix = f_pix; l_bad = f_bad; l_hs = f_hs; l_en = f_en; l_clk = f_clk;
                f_pix = 0; f_bad = 0; f_hs = 0; f_en = 0; f_clk = 0;
            end
            if (hsync && !hs_q) f_hs = f_hs + 1;
            if (pix_valid) begin
                f_pix = f_pix + 1;
                if (pix_index !== exp_pix) begin
                    if (f_bad < 4 && pass_flag) $display("  bad pixel #%0d: %h (exp %h)", f_pix, pix_index, exp_pix);
                    f_bad = f_bad + 1;
                end
            end
            if (dut.cpu_en) f_en = f_en + 1;
            f_clk = f_clk + 1;
        end
        vs_q = vsync; hs_q = hsync;
    end

    // random pause bursts while the program runs (CGB case)
    reg pause_test = 1'b0;
    always @(posedge clk) begin
        if (reset || !pause_test || pass_flag)
            pause <= 1'b0;
        else if (!pause && ($urandom % 3000) == 0)
            pause <= 1'b1;
        else if (pause && ($urandom % 100) == 0)
            pause <= 1'b0;
    end

    // ------------------------------------------------------------------
    // Test sequence
    // ------------------------------------------------------------------
    integer i, t, f0;
    reg [7:0] pat [0:7];

    task load_memory;
        begin
            for (i = 0; i < 32'h400000; i = i + 1) mem[i] = 8'h00;
            mem[22'h100] = 8'h00; mem[22'h101] = 8'hC3; mem[22'h102] = 8'h50; mem[22'h103] = 8'h01;
            mem[22'h143] = 8'h80; mem[22'h147] = 8'h19; mem[22'h148] = 8'h02; mem[22'h149] = 8'h02;
            for (i = 0; i < PROG_LEN; i = i + 1)
                mem[22'h150 + i] = PROG[8*(PROG_LEN-1-i) +: 8];
            for (i = 0; i < 16; i = i + 1) mem[22'h1000 + i] = 8'hFF;      // tile 0 = colour 3
            for (i = 0; i < 1024; i = i + 1) mem[22'h1800 + i] = 8'h05;    // attributes: palette 5
            mem[22'h4000] = 8'hB1;                                          // bank 1 signature
            mem[22'hC000] = 8'hB3;                                          // bank 3 signatures
            mem[22'hFFFF] = 8'h3C;
            for (i = 0; i < 8192; i = i + 1) begin
                dut.vram0[i] = 8'h00;
                dut.vram1[i] = 8'h00;
            end
            for (i = 0; i < 80; i = i + 1) begin
                dut.oam_e[i] = 8'h00;
                dut.oam_o[i] = 8'h00;
            end
            for (i = 0; i < 128; i = i + 1) dut.hram[i] = 8'h00;
            for (i = 0; i < 64; i = i + 1) begin
                dut.bgpal[i] = 8'h00;
                dut.objpal[i] = 8'h00;
            end
        end
    endtask

    task check_mem(input [21:0] a, input [7:0] v);
        if (mem[a] !== v) $fatal(1, "SDRAM[%h] = %h, expected %h", a, mem[a], v);
    endtask

    task run_case(input bit cgb);
        real rate, exp_rate;
        begin
            $display("--- %s run ---", cgb ? "CGB" : "DMG");
            reset = 1'b1;
            model_reset = 1'b1;
            cgb_enable = cgb;
            pause_test = cgb;
            exp_pix = cgb ? 6'h17 : 6'h01;
            load_memory();
            pal_n = 0;
            pass_flag = 1'b0;
            repeat (20) @(posedge clk);
            #1 reset = 1'b0; model_reset = 1'b0;

            for (t = 0; t < 3000000 && !pass_flag; t = t + 1) @(posedge clk);
            if (!pass_flag) $fatal(1, "timeout waiting for the test program (cgb=%0d)", cgb);
            $display("  program passed at %0t, cgb_mode=%0d, double_speed=%0d", $time, cgb_mode, dut.double_speed);
            if (cgb_mode !== cgb) $fatal(1, "cgb_mode output wrong");

            f0 = frames;
            for (t = 0; t < 2000000 && frames < f0 + 3; t = t + 1) @(posedge clk);
            if (frames < f0 + 3) $fatal(1, "timeout waiting for frames");
            rate = 1.0 * l_en / l_clk;
            exp_rate = cgb ? 32768.0 / 84375.0 : 16384.0 / 84375.0;
            $display("  frame: %0d pixels, %0d bad, %0d hsync, %0d clk, cpu_en rate %f (exp %f)",
                     l_pix, l_bad, l_hs, l_clk, rate, exp_rate);
            if (l_pix != 160 * 144) $fatal(1, "wrong pixel count per frame: %0d", l_pix);
            if (l_bad != 0) $fatal(1, "%0d pixels with wrong pix_index", l_bad);
            if (l_hs != 154) $fatal(1, "wrong hsync count per frame: %0d", l_hs);
            if (l_clk < 361000 || l_clk > 362500) $fatal(1, "wrong frame length: %0d clk", l_clk);
            if (rate < exp_rate * 0.97 || rate > exp_rate * 1.03) $fatal(1, "CPU speed out of range");

            if (cgb) begin
                check_mem(22'h3D8000, 8'h11);
                check_mem(22'h3DA000, 8'h22);
                check_mem(22'h3DF000, 8'h77);
                check_mem(22'h3E0000, 8'hA5);
                if (pal_n != 133) $fatal(1, "pal_wr count %0d, expected 133", pal_n);
                for (i = 0; i < 128; i = i + 1)
                    if (pal_a[i] !== i[6:0] || pal_d[i] !== pat[i % 8])
                        $fatal(1, "boot pal_wr #%0d: addr %h data %h", i, pal_a[i], pal_d[i]);
                if (pal_a[128] !== 7'h00 || pal_d[128] !== 8'h12 ||
                    pal_a[129] !== 7'h01 || pal_d[129] !== 8'h34 ||
                    pal_a[130] !== 7'h02 || pal_d[130] !== 8'h56 ||
                    pal_a[131] !== 7'h48 || pal_d[131] !== 8'h9A ||
                    pal_a[132] !== 7'h49 || pal_d[132] !== 8'hBC)
                    $fatal(1, "program pal_wr events wrong");
            end else begin
                check_mem(22'h3D8000, 8'h5A);
                check_mem(22'h3D9DFF, 8'hA5);
                if (pal_n != 0) $fatal(1, "pal_wr pulsed in DMG mode");
            end
            $display("  SDRAM: %0d reads (%0d worst-case latency), %0d writes", n_rd, n_worst, n_wr);
        end
    endtask

    initial begin
        pat[0] = 8'hFF; pat[1] = 8'h7F; pat[2] = 8'hB5; pat[3] = 8'h56;
        pat[4] = 8'h4A; pat[5] = 8'h29; pat[6] = 8'h00; pat[7] = 8'h00;
        run_case(1'b1);
        run_case(1'b0);
        $display("tb_gbc_core PASSED");
        $finish;
    end

    initial begin
        #400ms;
        $fatal(1, "global timeout");
    end

endmodule
