// Synthesis-only console boundary. These ports are not Nano 20K board pins.
module megadrive_probe (
    input  wire        mclk,
    input  wire        clk_z80,
    input  wire        reset_n,
    input  wire        pal,
    input  wire        export_region,
    input  wire        loading,
    input  wire        pause,
    input  wire [11:0] joy1,
    input  wire [11:0] joy2,
    input  wire [24:1] rom_size,
    output wire [24:1] mem_addr,
    input  wire [15:0] mem_rdata,
    output wire [15:0] mem_wdata,
    output wire        mem_we,
    output wire [1:0]  mem_be,
    output wire        mem_req,
    input  wire        mem_ack,
    output wire [3:0]  red,
    output wire [3:0]  green,
    output wire [3:0]  blue,
    output wire        hs,
    output wire        vs,
    output wire        hblank,
    output wire        vblank,
    output wire        ce_pix,
    output wire        interlace,
    output wire        field,
    output wire [1:0]  resolution,
    output wire [15:0] audio_left,
    output wire [15:0] audio_right
);

system u_console (
    .RESET_N(reset_n), .MCLK(mclk), .CLK_Z80(clk_z80),
    .LPF_MODE(2'b11), .ENABLE_FM(1'b1), .ENABLE_PSG(1'b1),
    .DAC_LDATA(audio_left), .DAC_RDATA(audio_right),
    .LOADING(loading), .PAL(pal), .EXPORT(export_region),
    .FAST_FIFO(1'b0), .SRAM_QUIRK(1'b0), .SRAM00_QUIRK(1'b0),
    .EEPROM_QUIRK(1'b0), .NORAM_QUIRK(1'b0), .PIER_QUIRK(1'b0),
    .SVP_QUIRK(1'b0), .FMBUSY_QUIRK(1'b0), .SCHAN_QUIRK(1'b0),
    .TURBO(2'b00),
    .GG_RESET(1'b0), .GG_EN(1'b0), .GG_CODE(129'b0), .GG_AVAILABLE(),
    .BRAM_A(15'b0), .BRAM_DI(16'b0), .BRAM_DO(),
    .BRAM_WE(1'b0), .BRAM_CHANGE(),
    .RED(red), .GREEN(green), .BLUE(blue),
    .VS(vs), .HS(hs), .HBL(hblank), .VBL(vblank), .CE_PIX(ce_pix),
    .BORDER(1'b0), .CRAM_DOTS(1'b0), .INTERLACE(interlace),
    .FIELD(field), .RESOLUTION(resolution),
    .J3BUT(1'b0), .JOY_1(joy1), .JOY_2(joy2),
    .JOY_3(12'b0), .JOY_4(12'b0), .JOY_5(12'b0), .MULTITAP(3'b0),
    .MOUSE(25'b0), .MOUSE_OPT(3'b0),
    .GUN_OPT(1'b0), .GUN_TYPE(1'b0), .GUN_SENSOR(1'b0),
    .GUN_A(1'b0), .GUN_B(1'b0), .GUN_C(1'b0), .GUN_START(1'b0),
    .SERJOYSTICK_IN(8'b0), .SERJOYSTICK_OUT(), .SER_OPT(2'b0),
    .ROMSZ(rom_size), .MEM_ADDR(mem_addr), .MEM_DATA(mem_rdata),
    .MEM_WDATA(mem_wdata), .MEM_WE(mem_we), .MEM_BE(mem_be),
    .MEM_REQ(mem_req), .MEM_ACK(mem_ack),
    .EN_HIFI_PCM(1'b0), .LADDER(1'b0), .OBJ_LIMIT_HIGH(1'b0),
    .TRANSP_DETECT(), .PAUSE_EN(pause),
    .BGA_EN(1'b1), .BGB_EN(1'b1), .SPR_EN(1'b1),
    .DBG_M68K_A(), .DBG_VBUS_A()
);

endmodule
